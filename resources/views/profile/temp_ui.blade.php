			}

			if(m == undefined){
				alert_danger('no client id list found');
				return;
			}

			let clients = m.filter(f => {
				if(demopage_thefilter == "all" || demopage_thefilter == undefined){
					return true;
				} else {
					return f.client_class.toLowerCase() == demopage_thefilter.toLowerCase();
				}
			});

			/*
