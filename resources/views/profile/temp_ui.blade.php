	function renderclients(d) {
		if(d == undefined){
			d = demopage_cached_last_data || null;
		}

		if(d == null){
			alert_info('no client data passed');
			return;
		}

		demopage_cached_last_data = d;
		// alert_info('getting clients');
		let snd = d.sendme;
		let sum = 0;

		snd.forEach(c => {
			sum += Number(c.credit_balance);
		});

		let newshape = {
			"total_owed":sum,
			"debtors": snd
		};
		d.sendme = newshape;

		console.log('latest datashape',d);

